const DICTS: Record<string, Dict> = { en, hi };

export const LANGUAGES = [
  { value: "en", label: "English" },
  { value: "hi", label: "हिन्दी" },
] as const;

export function resolveLang(setting: string | undefined): "en" | "hi" {
  if (setting === "en" || setting === "hi") return setting;
  return navigator.language?.toLowerCase().startsWith("hi") ? "hi" : "en";
}

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translate(lang: string, key: Key, vars?: Record<string, string | number>): string {
  let s = DICTS[lang]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Translate a backend stage label; unknown stages are shown as-is. */
export function stageLabel(t: T, stage: string | null | undefined): string {
  if (!stage) return "…";
  const key = `stage.${stage}` as Key;
  return key in en ? t(key) : stage;
}

/** Hook: re-renders when the language setting changes. */
export function useT(): T {
  const lang = resolveLang(useStore((s) => s.settings?.language));
  return (key, vars) => translate(lang, key, vars);
}

/** For non-React code (toasts from async handlers). */
export function tNow(key: Key, vars?: Record<string, string | number>): string {
  return translate(resolveLang(useStore.getState().settings?.language), key, vars);
}
